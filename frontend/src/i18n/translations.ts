/**
 * 常驻字典：中英两份随首包加载，其余 14 种走动态 import（见 ensureLanguageLoaded）。
 * 首包因此只背两份字典，切到日/德/阿等语言时按需拉一个约 20 KB 的 chunk。
 */
const DICT: Partial<Record<ResolvedLanguage, TranslationTable>> = {
  'zh-CN': ZH_CN_DICT,
  en: EN_DICT,
};

const LAZY_LOADERS: Record<string, () => Promise<{ dict: TranslationTable }>> = {
  'zh-TW': () => import('./locales/zh-TW'),
  ja: () => import('./locales/ja'),
  ko: () => import('./locales/ko'),
  es: () => import('./locales/es'),
  fr: () => import('./locales/fr'),
  de: () => import('./locales/de'),
  ru: () => import('./locales/ru'),
  'pt-BR': () => import('./locales/pt-BR'),
  it: () => import('./locales/it'),
  ar: () => import('./locales/ar'),
  vi: () => import('./locales/vi'),
  tr: () => import('./locales/tr'),
  pl: () => import('./locales/pl'),
  nl: () => import('./locales/nl'),
};

const LAZY_DICTS: Partial<Record<ResolvedLanguage, TranslationTable>> = {};
const inflight = new Map<string, Promise<void>>();

/** 按需载入某种语言的字典；中英已常驻，直接 resolve。 */
export function ensureLanguageLoaded(lang: ResolvedLanguage): Promise<void> {
  if (DICT[lang] || LAZY_DICTS[lang]) return Promise.resolve();
  const loader = LAZY_LOADERS[lang];
  if (!loader) return Promise.resolve();
  const existing = inflight.get(lang);
  if (existing) return existing;
  const task = loader()
    .then((mod) => {
      LAZY_DICTS[lang] = mod.dict;
    })
    .catch(() => {
      // 加载失败就回落英文，绝不阻塞渲染
    })
    .finally(() => {
      inflight.delete(lang);
    });
  inflight.set(lang, task);
  return task;
}

/** 该语言的字典是否已就绪（用于避免切换瞬间闪英文）。 */
export function isLanguageLoaded(lang: ResolvedLanguage): boolean {
  return Boolean(DICT[lang] || LAZY_DICTS[lang]);
}

export function translate(
  lang: ResolvedLanguage,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const table = LAZY_DICTS[lang] || DICT[lang] || DICT.en;
  let text: string = table?.[key] || EN_DICT[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}
