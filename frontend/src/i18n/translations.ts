export function normalizeLanguageCode(raw?: string | null): ResolvedLanguage | null {
  if (!raw) return null;
  const trimmed = String(raw).trim();
  if (!trimmed || trimmed.toLowerCase() === 'auto') return null;
  const lower = trimmed.toLowerCase();
  if (lower in LANG_ALIAS_MAP) {
    return LANG_ALIAS_MAP[lower];
  }
  const primary = lower.split('-')[0].split('_')[0];
  if (primary in LANG_ALIAS_MAP) {
    return LANG_ALIAS_MAP[primary];
  }
  return null;
}

export function isChineseLanguage(lang: ResolvedLanguage): boolean {
  return lang === 'zh-CN' || lang === 'zh-TW';
}

export function isRtlLanguage(lang: ResolvedLanguage): boolean {
  return lang === 'ar';
}

export function getLanguageMeta(lang: ResolvedLanguage): SupportedLanguageMeta {
  return SUPPORTED_LANGUAGES.find((item) => item.id === lang) || SUPPORTED_LANGUAGES[0];
}

export function detectBrowserLanguage(): ResolvedLanguage {
  if (typeof navigator !== 'undefined' && navigator.language) {
    const matched = normalizeLanguageCode(navigator.language);
    if (matched) return matched;
  }
  return 'en';
}

export function detectOSPlatform(): OSPlatform {
  if (typeof navigator !== 'undefined') {
    const ua = (navigator.userAgent || navigator.platform || '').toLowerCase();
    if (ua.includes('win')) return 'win';
    if (ua.includes('linux')) return 'linux';
  }
  return 'mac';
}

export function resolveLanguage(pref: LanguageOption | string, ankiResolved?: string): ResolvedLanguage {
  const fromPref = normalizeLanguageCode(pref);
  if (fromPref) return fromPref;
  const fromAnki = normalizeLanguageCode(ankiResolved);
  if (fromAnki) return fromAnki;
  return detectBrowserLanguage();
}

/**
 * Formats keyboard shortcut strings dynamically for macOS (`Cmd`, `Option`, `Ctrl Opt M`)
 * vs Windows/Linux (`Ctrl`, `Alt`, `Ctrl Alt M`).
 */
export function formatShortcut(shortcut: string, platform: OSPlatform = 'mac'): string {
  if (platform === 'mac') return shortcut;
  return shortcut
    .replace(/\bCmd\b/g, 'Ctrl')
    .replace(/\bOption\b/g, 'Alt')
    .replace(/\bOpt\b/g, 'Alt');
}

